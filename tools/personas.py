"""Personas and journeys from one source (documentation/solution/personas.json): writes the persona and journey sections
of the user research bundle, adds the newer stages to the service blueprint, and checks that every route a persona
is offered leads to a page, view, section, tab or sector that exists. The portal's 'Start here' panel reads the same
file. --negative proves the checks fail when they should."""
import copy, json, pathlib, re, sys, urllib.parse

ROOT = pathlib.Path(__file__).resolve().parents[1]; SOL = ROOT / "documentation/solution"
P = json.loads((SOL / "personas.json").read_text())
START, END = "<!-- personas:start (generated by tools/personas.py from personas.json) -->", "<!-- personas:end -->"


def check(p):
    e = []
    docs = {f.name: f.read_text() for f in (ROOT / "docs").glob("*.html")}
    views = set(re.findall(r'<section class="view" id="v-([a-z]+)"', docs.get("index.html", "")))
    fund = json.loads((ROOT / "data/funding.json").read_text())
    for x in p["personas"]:
        if not x["routes"]: e.append(f"{x['id']}: no routes")
        for label, href in x["routes"]:
            page, _, frag = href.partition("#")
            if page not in docs: e.append(f"{x['id']}: {label}: page {page} does not exist"); continue
            if page == "index.html" and frag and frag not in views: e.append(f"{x['id']}: {label}: view #{frag} does not exist")
            if page == "nations.html" and frag and f'id="{frag}"' not in docs[page]: e.append(f"{x['id']}: {label}: section #{frag} does not exist")
            if page in ("funding.html", "orgchart.html") and frag:
                q = dict(urllib.parse.parse_qsl(frag))
                if page == "funding.html" and q.get("tab") not in (None, "grants", "schemes", "services", "funders"): e.append(f"{x['id']}: unknown funding tab")
                if page == "funding.html" and q.get("sector") and q["sector"] not in fund["sectors"]: e.append(f"{x['id']}: unknown sector {q['sector']}")
                if page == "orgchart.html" and q.get("view") not in (None, "answers", "nations", "types", "world"): e.append(f"{x['id']}: unknown org chart view")
    ids = [x["id"] for x in p["personas"]]
    if len(ids) != len(set(ids)): e.append("a persona id is repeated")
    return e


def md(p):
    rows = "\n".join(f"| {x['group']} | **{x['who']}** | {x['goal']} | {'; '.join(x['tasks'])} | {'; '.join(f'[{a}](../../docs/{b})' for a, b in x['routes'])} | {x['success']} | {x['test']} |" for x in p["personas"])
    js = "\n".join(f"{i}. **{j['name']}:** {' → '.join(j['steps'])}." for i, j in enumerate(p["journeys"], 1))
    return (f"{START}\n## Proto-personas\n\n{p['status']}\n\n| Group | Who | Goal | Top tasks | Where the portal takes them | Success looks like | Hypothesis to test |\n|---|---|---|---|---|---|---|\n{rows}\n\n"
            f"## Journeys (hypothesised)\n\n{js}\n{END}")


def main():
    if "--negative" in sys.argv:
        cases = []
        x = copy.deepcopy(P); x["personas"][0]["routes"].append(["broken", "index.html#nowhere"]); cases.append(x)
        x = copy.deepcopy(P); x["personas"][0]["routes"].append(["broken", "funding.html#tab=services&sector=nope"]); cases.append(x)
        x = copy.deepcopy(P); x["personas"].append(copy.deepcopy(x["personas"][0])); cases.append(x)
        if not all(check(c) for c in cases): sys.exit("personas negative: a breaker was not caught")
        print(f"personas negative: all {len(cases)} breakers caught"); return
    e = check(P)
    if e: sys.exit("personas: " + "; ".join(e))
    f = SOL / "02-user-research.md"; s = f.read_text()
    block = md(P)
    if START in s: s = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, s, flags=re.S)
    else: s = re.sub(r"## Proto-personas.*?(?=## Research plan)", lambda _: block + "\n\n", s, flags=re.S)
    f.write_text(s)
    print(f"personas: {len(P['personas'])} personas, {len(P['journeys'])} journeys, {sum(len(x['routes']) for x in P['personas'])} routes checked")


if __name__ == "__main__":
    main()
